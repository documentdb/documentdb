typedef enum QueryCursorType
{
	QueryCursorType_Unspecified = 0,

	/*
	 * Whether or not the query can be done as a streamable
	 * query.
	 */
	QueryCursorType_Streamable = 1,

	/*
	 * Indicates whether this is processed as a single batch query.
	 */
	QueryCursorType_SingleBatch,

	/*
	 * The cursor plan is a point read.
	 */
	QueryCursorType_PointRead,

	/*
	 * Whether or not the query can be done as a tailable
	 * query.
	 */
	QueryCursorType_Tailable,

	/*
	 * By default all queries are persistent cursors.
	 */
	QueryCursorType_Persistent,

	/*
	 * Indicates that the query may need to switch between persistent
	 * and streaming behavior depending on the execution context.
	 */
	QueryCursorType_Dynamic,
} QueryCursorType;


/*
 * The kind of cursor parameters that should be generated by the query.
 */
typedef enum CursorParamKind
{
	/* The cursor parameters should be geared towards a persistent cursor.
	 * This is the default behavior and works like regular Postgres queries.
	 */
	CursorParamKind_Persistent = 0,

	/*
	 * The cursor parameters should be geared towards a streaming cursor.
	 * This is used when the query is expected to return results in a
	 * streamable fashion for simple finds and aggregates.
	 */
	CursorParamKind_Streaming = 1,

	/*
	 * The cursor parameters should be geared towards a dynamic cursor.
	 * This is used when the query may need to switch between persistent
	 * and streaming behavior depending on the execution context.
	 */
	CursorParamKind_Dynamic = 2,
} CursorParamKind;

/*
 * Tracks the collection topology relevant to cursor behavior.
 * This is set during initial query generation and then reported
 * during getMore operations.
 */
typedef enum CursorTopology
{
	CursorTopology_Unknown = 0,
	CursorTopology_LocalUnsharded,
	CursorTopology_RemoteUnsharded,
	CursorTopology_ShardedWithShardKeyEquality,
	CursorTopology_ShardedWithInOnShardKey,
	CursorTopology_GeneralSharded,
} CursorTopology;

/*
 * Tracks the overall query spec data
 * that can be extracted from the query.
 * Used in cursor management to page and
 * decide what kind of cursor to use for the outer
 * request.
 */
typedef struct
{
	/*
	 * The parameter number used for the cursor
	 * continuation (if it is a streaming cursor)
	 */
	int cursorStateParamNumber;

	/* Optional cursor state const param */
	pgbson *cursorStateConst;

	/*
	 * The namespaceName associated with the query.
	 */
	const char *namespaceName;

	QueryCursorType cursorKind;

	/*
	 * The collection topology for this cursor query.
	 */
	CursorTopology cursorTopology;

	/*
	 * The requested batchSize in the query request.
	 */
	int32_t batchSize;

	/*
	 * The maxAwaitTimeMS in the query request for tailable cursors.
	 */
	int64_t maxAwaitTimeMS;

	/*
	 * The time system variables ($$NOW, $$CLUSTER_TIME).
	 */
	TimeSystemVariables timeSystemVariables;

	/*
	 * Whether this query is being built from the planner aggregation
	 * query cursor rewrite path (enableCursorsOnAggregationQueryRewrite).
	 */
	bool isAggregationQueryCursorRewrite;

	/*
	 * Whether a dynamic streaming cursor has returned a row on any prior page.
	 */
	bool hasFetchedRows;

	/*
	 * Top-level find limit tracked across pages in the "lim" continuation field.
	 * Zero means untracked.
	 */
	int64_t streamingLimit;

	/*
	 * Top-level find skip tracked while planning.
	 */
	int64_t streamingSkip;
} QueryData;


